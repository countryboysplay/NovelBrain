  await expect(channels.getByRole('button', { name: /^channel reviews\W+1 unread$/ })).toBeVisible()
  // #general: one thread per step; the latest is open, an older one opens on its button.
  const older = log.getByRole('button', { name: 'SC-001 · The Field · 3 messages' })
  await expect(older).toHaveAttribute('aria-expanded', 'false')
  await expect(log.getByText('DRAFTED SC-001 round 1')).toBeHidden()
