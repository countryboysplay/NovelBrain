test('cost: a Codeburn sheet that failed to load comes back when Restart Codeburn is pressed, even with the status still up', async () => {
  const book = await studioBook()
  const { app, win } = await launch(book)
  await nav(win, 'Cost')
  const frame = win.locator('.codeburn-frame')
  await expect(frame).not.toHaveClass(/loading/)
  // The guest has its own in-memory session, so its deny-all permission handlers never reach the studio's (terminal copy needs clipboard-sanitized-write).
  expect(await app.evaluate(({ session, webContents }) => webContents.getAllWebContents().filter(w => w.getType() === 'webview').map(w => [w.session === session.fromPartition('codeburn'), w.session !== session.defaultSession]))).toEqual([[true, true]])
  await win.evaluate(() => document.querySelector('webview')!.dispatchEvent(new Event('did-fail-load'))) // a dead port, as Electron reports it
  await expect(win.locator('#view')).toContainText('did not answer on port')
  await app.evaluate(({ ipcMain }) => { ipcMain.removeHandler('service:restart'); ipcMain.handle('service:restart', () => undefined) }) // the status stays up on the same port: only the sheet itself can recover
  await win.getByRole('button', { name: 'Restart Codeburn' }).click()
  await expect(win.locator('webview')).toBeVisible() // the sheet is back (the stub answers too fast for the loading state to be seen here)
  await expect(frame).not.toHaveClass(/loading/)
  await expect(win.locator('#view')).not.toContainText('did not answer on port')
  await app.close()
})

